<#
.SYNOPSIS
  Build the Revit MCP product: Autodesk .bundle, per-user MSI, and store zip.

.DESCRIPTION
  One command from a clean checkout (needs .NET SDK 10 and Python 3.11; NuGet
  and PyPI access on first run):

      powershell -ExecutionPolicy Bypass -File installer\build.ps1 [-Test]

  Steps:
    1. Version from the repo VERSION file -> add-in assembly, server exe, MSI, bundle.
    2. Add-in built for every Revit version in installer\product.json
       (2025/2026 = .NET 8, 2027 = .NET 10).
    3. MCP server frozen with PyInstaller into revit-mcp-server.exe, from the
       exact dependency versions in installer\requirements-server.lock, in an
       isolated build venv (build\pyenv). Nobody needs Python installed.
    4. Autodesk bundle staged: build\stage\RevitMCP.bundle
         PackageContents.xml
         Contents\<year>\RevitMCP.addin + RevitMCP.Addin.dll
         Contents\Server\revit-mcp-server.exe (+ _internal\)
         Contents\Resources\help.html, revitmcp.ico
    5. Code signing (installer\sign.ps1; skipped with a warning if not configured).
    6. MSI: dist\RevitMCP-<version>.msi (WiX v5, per-user, no admin).
    7. Store package: dist\RevitMCP-<version>-bundle.zip, plus SHA256SUMS.txt.
    8. -Test: unit tests + the end-to-end governance test against the built exe.

  Nothing is installed on this machine. Outputs go to build\ and dist\ (git-ignored).

.PARAMETER RevitVersions
  Subset of Revit versions to build (default: all in product.json).
.PARAMETER SkipServer
  Reuse the previously frozen server (faster when only the add-in changed).
.PARAMETER SkipMsi
  Stop after staging the bundle.
.PARAMETER RequireSigning
  Fail if code signing is not configured (use for release builds).
.PARAMETER Test
  Run the Python unit tests and the governance end-to-end test against the exe.
#>
param(
  [string[]]$RevitVersions,
  [switch]$SkipServer,
  [switch]$SkipMsi,
  [switch]$RequireSigning,
  [switch]$Test
)

$ErrorActionPreference = "Stop"
$repo = Split-Path -Parent $PSScriptRoot
$installer = $PSScriptRoot
$utf8 = New-Object System.Text.UTF8Encoding($false)

function Step($text) { Write-Host "==> $text" -ForegroundColor Cyan }
function Write-Utf8($path, $text) {
  New-Item -ItemType Directory -Force -Path (Split-Path -Parent $path) | Out-Null
  [System.IO.File]::WriteAllText($path, $text, $utf8)
}
function Invoke-Checked([string]$what, [scriptblock]$block) {
  & $block
  if ($LASTEXITCODE -ne 0) { throw "$what failed (exit $LASTEXITCODE)." }
}
function Esc([string]$s) { [System.Security.SecurityElement]::Escape($s) }
function NameGuid([string]$name) {
  # Deterministic GUID from a name (same input -> same GUID across builds).
  $md5 = [System.Security.Cryptography.MD5]::Create()
  $bytes = $md5.ComputeHash([System.Text.Encoding]::UTF8.GetBytes($name))
  return ([guid]::new($bytes)).ToString().ToUpper()
}

# ---------------------------------------------------------------- 1. version
$version = (Get-Content (Join-Path $repo "VERSION") -Raw).Trim()
if ($version -notmatch '^\d+\.\d+\.\d+$') { throw "VERSION must be MAJOR.MINOR.PATCH (MSI requirement), got '$version'." }
$product = Get-Content (Join-Path $installer "product.json") -Raw | ConvertFrom-Json
if (-not $RevitVersions) { $RevitVersions = @($product.revit_versions) }
$todo = @($product.publisher, $product.publisher_url, $product.support_email, $product.help_url) | Where-Object { $_ -match 'TODO' }
if ($todo) { Write-Warning "installer\product.json still has TODO publisher fields; fine for internal builds, not for the store." }

$build = Join-Path $repo "build"
$dist = Join-Path $repo "dist"
$stage = Join-Path $build "stage"
$bundle = Join-Path $stage "RevitMCP.bundle"
$contents = Join-Path $bundle "Contents"
Step "Revit MCP $version for Revit $($RevitVersions -join ', ')"
if (Test-Path $stage) { Remove-Item $stage -Recurse -Force }
New-Item -ItemType Directory -Force -Path $contents, $dist | Out-Null

Write-Utf8 (Join-Path $repo "server\revit_mcp\_version.py") "# Generated by installer/build.ps1 from VERSION. Do not edit.`n__version__ = `"$version`"`n"

# ---------------------------------------------------------------- 2. add-in
$csproj = Join-Path $repo "addin\RevitMCP.Addin.csproj"
foreach ($rv in $RevitVersions) {
  Step "Add-in for Revit $rv"
  Invoke-Checked "dotnet build (Revit $rv)" { dotnet build $csproj -c Release -p:RevitVersion=$rv -p:Version=$version -nologo -v:q | Out-Host }
  $out = Join-Path $contents $rv
  New-Item -ItemType Directory -Force -Path $out | Out-Null
  Copy-Item (Join-Path $repo "addin\bin\Release\$rv\RevitMCP.Addin.dll") $out
  Write-Utf8 (Join-Path $out "RevitMCP.addin") @"
<?xml version="1.0" encoding="utf-8"?>
<RevitAddIns>
  <AddIn Type="Application">
    <Name>Revit MCP</Name>
    <Assembly>RevitMCP.Addin.dll</Assembly>
    <FullClassName>RevitMCP.Addin.RevitMcpApp</FullClassName>
    <ClientId>$($product.addin_client_id)</ClientId>
    <VendorId>$(Esc $product.addin_vendor_id)</VendorId>
    <VendorDescription>$(Esc $product.publisher), $(Esc $product.publisher_url)</VendorDescription>
  </AddIn>
</RevitAddIns>
"@
}

# ---------------------------------------------------------------- 3. server exe
$pyiDist = Join-Path $build "pyi\dist\revit-mcp-server"
if (-not $SkipServer) {
  Step "MCP server -> revit-mcp-server.exe (PyInstaller)"
  $pyenv = Join-Path $build "pyenv"
  $py = Join-Path $pyenv "Scripts\python.exe"
  if (-not (Test-Path $py)) {
    $devPy = Join-Path $repo "server\.venv\Scripts\python.exe"
    $basePy = if ($env:REVITMCP_PYTHON) { $env:REVITMCP_PYTHON }
              elseif (Test-Path $devPy) { Join-Path (& $devPy -c "import sys; print(sys.base_prefix)") "python.exe" }
              else { "python" }
    Invoke-Checked "create build venv" { & $basePy -m venv $pyenv }
  }
  Invoke-Checked "pip install (locked deps)" {
    & $py -m pip install -q --disable-pip-version-check -r (Join-Path $installer "requirements-server.lock") "pyinstaller==6.22.3"
  }
  Invoke-Checked "pip install server" { & $py -m pip install -q --disable-pip-version-check --no-deps -e (Join-Path $repo "server") }

  $v4 = ($version.Split('.') + @('0')) -join ', '
  $verFile = Join-Path $build "pyi\version_info.txt"
  Write-Utf8 $verFile @"
VSVersionInfo(
  ffi=FixedFileInfo(filevers=($v4), prodvers=($v4), mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', '$($product.publisher -replace "'", "")'),
      StringStruct('FileDescription', 'Revit MCP server (connects Claude to Revit)'),
      StringStruct('FileVersion', '$version'),
      StringStruct('InternalName', 'revit-mcp-server'),
      StringStruct('OriginalFilename', 'revit-mcp-server.exe'),
      StringStruct('ProductName', 'Revit MCP'),
      StringStruct('ProductVersion', '$version')])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"@
  Invoke-Checked "PyInstaller" {
    & $py -m PyInstaller --noconfirm --clean --log-level WARN --onedir --console --name revit-mcp-server `
      --paths (Join-Path $repo "server") `
      --distpath (Join-Path $build "pyi\dist") --workpath (Join-Path $build "pyi\work") --specpath (Join-Path $build "pyi") `
      --icon (Join-Path $installer "assets\revitmcp.ico") --version-file $verFile `
      --hidden-import anyio._backends._asyncio --exclude-module tkinter --exclude-module pytest `
      (Join-Path $installer "server_entry.py")
  }
}
if (-not (Test-Path (Join-Path $pyiDist "revit-mcp-server.exe"))) { throw "No frozen server at $pyiDist (run without -SkipServer)." }
$exeVersion = (& (Join-Path $pyiDist "revit-mcp-server.exe") --version).Trim()
if ($exeVersion -ne "Revit MCP server $version") { throw "Frozen server reports '$exeVersion', expected $version (rebuild without -SkipServer)." }
Copy-Item $pyiDist (Join-Path $contents "Server") -Recurse

# ---------------------------------------------------------------- 4. resources + PackageContents
Step "Bundle resources and PackageContents.xml"
$res = Join-Path $contents "Resources"
$help = (Get-Content (Join-Path $installer "bundle\help.html") -Raw -Encoding UTF8).
  Replace("{{VERSION}}", $version).Replace("{{PUBLISHER}}", (Esc $product.publisher)).Replace("{{SUPPORT_EMAIL}}", (Esc $product.support_email))
Write-Utf8 (Join-Path $res "help.html") $help
Copy-Item (Join-Path $installer "assets\revitmcp.ico") $res

$sorted = $RevitVersions | Sort-Object
$componentsXml = ($sorted | ForEach-Object {
@"
  <Components Description="Revit $_">
    <RuntimeRequirements OS="Win64" Platform="Revit" SeriesMin="R$_" SeriesMax="R$_" />
    <ComponentEntry AppName="Revit MCP" Version="$version" ModuleName="./Contents/$_/RevitMCP.addin" AppDescription="$(Esc $product.description)" />
  </Components>
"@
}) -join "`n"
Write-Utf8 (Join-Path $bundle "PackageContents.xml") @"
<?xml version="1.0" encoding="utf-8"?>
<ApplicationPackage SchemaVersion="1.0" AutodeskProduct="Revit" ProductType="Application"
                    Name="Revit MCP" Description="$(Esc $product.description)"
                    AppVersion="$version" FriendlyVersion="$version" Author="$(Esc $product.publisher)"
                    ProductCode="{$(NameGuid "RevitMCP.bundle/$version")}" UpgradeCode="{$($product.bundle_upgrade_code)}"
                    HelpFile="./Contents/Resources/help.html" Icon="./Contents/Resources/revitmcp.ico"
                    OnlineDocumentation="$(Esc $product.help_url)" SupportedLocales="Enu">
  <CompanyDetails Name="$(Esc $product.publisher)" Url="$(Esc $product.publisher_url)" Email="$(Esc $product.support_email)" />
  <RuntimeRequirements OS="Win64" Platform="Revit" SeriesMin="R$($sorted[0])" SeriesMax="R$($sorted[-1])" />
$componentsXml
</ApplicationPackage>
"@

# ---------------------------------------------------------------- 5. sign binaries
Step "Code signing (binaries)"
$ours = @(Get-ChildItem $contents -Recurse -Filter RevitMCP.Addin.dll | ForEach-Object FullName) + (Join-Path $contents "Server\revit-mcp-server.exe")
& (Join-Path $installer "sign.ps1") -Files $ours -Require:$RequireSigning

# ---------------------------------------------------------------- 6. MSI
$msi = $null
if (-not $SkipMsi) {
  Step "MSI (WiX v5)"
  $wixproj = Join-Path $installer "msi\RevitMCP.Installer.wixproj"
  Invoke-Checked "WiX build" {
    dotnet build $wixproj -c Release -nologo -v:q "-p:ProductVersion=$version" "-p:BundleDir=$bundle" `
      "-p:Publisher=$($product.publisher)" "-p:UpgradeCode=$($product.msi_upgrade_code)" `
      "-p:HelpUrl=$($product.help_url)" "-p:AboutUrl=$($product.publisher_url)" | Out-Host
  }
  $built = Get-ChildItem (Join-Path $installer "msi\bin") -Recurse -Filter "RevitMCP-$version.msi" | Sort-Object LastWriteTime -Descending | Select-Object -First 1
  if (-not $built) { throw "MSI not found under installer\msi\bin." }
  $msi = Join-Path $dist $built.Name
  Copy-Item $built.FullName $msi -Force
  Step "Code signing (MSI)"
  & (Join-Path $installer "sign.ps1") -Files @($msi) -Require:$RequireSigning
}

# ---------------------------------------------------------------- 7. store zip + checksums
Step "Store package and checksums"
$zip = Join-Path $dist "RevitMCP-$version-bundle.zip"
if (Test-Path $zip) { Remove-Item $zip -Force }
Compress-Archive -Path $bundle -DestinationPath $zip
$outputs = @($zip) + @($msi | Where-Object { $_ })
$sums = $outputs | ForEach-Object { "{0}  {1}" -f (Get-FileHash $_ -Algorithm SHA256).Hash.ToLower(), (Split-Path $_ -Leaf) }
Write-Utf8 (Join-Path $dist "SHA256SUMS.txt") (($sums -join "`n") + "`n")

# ---------------------------------------------------------------- 8. tests
if ($Test) {
  $devPy = Join-Path $repo "server\.venv\Scripts\python.exe"
  if (-not (Test-Path $devPy)) { throw "-Test needs the dev venv (server\.venv) for pytest." }
  Push-Location (Join-Path $repo "server")
  try {
    Step "Unit tests"
    Invoke-Checked "pytest" { & $devPy -m pytest -q tests | Out-Host }
    Step "End-to-end governance test against the built exe"
    $env:REVIT_MCP_SERVER_EXE = Join-Path $contents "Server\revit-mcp-server.exe"
    Invoke-Checked "governance e2e" { & $devPy -m tools.test_governance | Select-Object -Last 3 | Out-Host }
  }
  finally { Remove-Item Env:REVIT_MCP_SERVER_EXE -ErrorAction SilentlyContinue; Pop-Location }
}

Step "Done"
$outputs | ForEach-Object { Write-Host ("    {0}  ({1:N1} MB)" -f $_, ((Get-Item $_).Length / 1MB)) -ForegroundColor Green }
Write-Host "    bundle: $bundle" -ForegroundColor Green
